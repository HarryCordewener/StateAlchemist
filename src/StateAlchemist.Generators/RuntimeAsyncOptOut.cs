namespace StateAlchemist.Generators;

/// <summary>
/// The attribute that keeps a method off runtime async. With <c>runtime-async=on</c> (.NET 11) the compiler marks
/// every async method for the runtime to run and ignores <c>[AsyncMethodBuilder]</c>, so the pooled methods the
/// generator writes would allocate on every suspension; <c>[RuntimeAsyncMethodGeneration(false)]</c> keeps them
/// compiler state machines. The compiler recognises the attribute by name. .NET 11 declares it only internally, so a
/// compilation that writes a machine and cannot see one gets this copy, internal to it.
/// </summary>
internal static class RuntimeAsyncOptOut
{
    public const string MetadataName = "System.Runtime.CompilerServices.RuntimeAsyncMethodGenerationAttribute";

    public const string HintName = "StateAlchemist.RuntimeAsyncMethodGenerationAttribute.g.cs";

    // The same shape as the runtime's own: methods only, one bool.
    public const string Source = """
        // <auto-generated/>
        // Generated by StateAlchemist: keeps the machine's pooled async methods off runtime async on .NET 11.
        #if NET11_0_OR_GREATER
        namespace System.Runtime.CompilerServices
        {
            [global::System.AttributeUsage(global::System.AttributeTargets.Method, AllowMultiple = false, Inherited = false)]
            internal sealed class RuntimeAsyncMethodGenerationAttribute : global::System.Attribute
            {
                public RuntimeAsyncMethodGenerationAttribute(bool runtimeAsync)
                {
                }
            }
        }
        #endif

        """;
}
